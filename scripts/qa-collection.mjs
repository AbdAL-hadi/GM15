import { chromium, expect } from '@playwright/test'
import { writeFile } from 'node:fs/promises'
const browser=await chromium.launch({channel:'msedge',headless:true}),errors=[]
for(const width of [390,1440]){
 const page=await browser.newPage({viewport:{width,height:900}})
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://127.0.0.1:4180/shop')
 await expect(page.locator('.product-card')).toHaveCount(12)
 expect(await page.locator('img.product-photo').evaluateAll(imgs=>imgs.every(i=>i.complete&&i.naturalWidth>0))).toBe(true)
 await page.screenshot({path:`verification/screenshots/collection-shop-${width}.png`,fullPage:true})
 await page.goto('http://127.0.0.1:4180/product/sudra')
 await expect(page.locator('h1')).toHaveText('SUDRA')
 await page.screenshot({path:`verification/screenshots/collection-product-${width}.png`,fullPage:true})
 await page.getByRole('button',{name:'حفظ في المفضلة'}).click()
 await page.getByRole('button',{name:'أضف إلى الحقيبة'}).click()
 await page.keyboard.press('Escape')
 await page.getByRole('button',{name:'استكشف 360°'}).click()
 await expect(page.locator('canvas')).toBeVisible()
 await page.getByRole('button',{name:'افتح الغطاء',exact:true}).click()
 await page.getByRole('button',{name:'جرّب الرشّة',exact:true}).click()
 await page.getByRole('button',{name:'إعادة ضبط المشهد'}).click()
 await page.goto('http://127.0.0.1:4180/journey/sudra')
 await expect(page.getByRole('heading',{name:'تين',exact:true})).toBeVisible()
 await page.screenshot({path:`verification/screenshots/collection-journey-${width}.png`,fullPage:true})
 await page.getByRole('button',{name:'القلب',exact:true}).click()
 await expect(page.getByRole('heading',{name:'ياسمين سامباك',exact:true})).toBeVisible()
 await page.evaluate(()=>localStorage.setItem('thetia-discover-v1',JSON.stringify({version:1,step:4,savedResult:'shams',answers:{moods:['vanilla'],likes:['vanilla'],likesUnsure:false,dislikes:[],dislikesNone:true,occasion:'any',budget:'any'}})))
 await page.goto('http://127.0.0.1:4180/discover/results')
 await expect(page.locator('.results-copy h2')).toHaveText('SUKOON')
 await expect(page.locator('.results-visual img')).toHaveAttribute('src','/products/sukoon.jpg')
 await page.goto('http://127.0.0.1:4180/layering')
 await expect(page.getByRole('heading',{name:'تنسيقات المجموعة الجديدة ستضاف لاحقًا'})).toBeVisible()
 expect(await page.evaluate(()=>globalThis.document.documentElement.scrollWidth<=globalThis.innerWidth)).toBe(true)
 await page.close()
}
await browser.close();await writeFile('verification/collection-browser.json',JSON.stringify({errors,widths:[390,1440]},null,2));expect(errors).toEqual([])
console.log('PASS collection catalog, images, product, cart, favorite, 360, journey, results and empty layering at both widths')
